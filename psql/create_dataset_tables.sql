CREATE TABLE IF NOT EXISTS public.datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_datasets_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_datasets_name_lower
    ON public.datasets (lower(name));

CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youtube_id VARCHAR(11) NOT NULL UNIQUE,
    url TEXT NOT NULL,
    title VARCHAR(255),
    duration_seconds INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_videos_youtube_id_format
        CHECK (youtube_id ~ '^[A-Za-z0-9_-]{11}$'),
    CONSTRAINT ck_videos_duration_nonnegative
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0)
);

CREATE TABLE IF NOT EXISTS public.dataset_videos (
    dataset_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_dataset_videos PRIMARY KEY (dataset_id, video_id),
    CONSTRAINT fk_dataset_videos_dataset
        FOREIGN KEY (dataset_id)
        REFERENCES public.datasets (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_dataset_videos_video
        FOREIGN KEY (video_id)
        REFERENCES public.videos (id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_dataset_videos_video_id
    ON public.dataset_videos (video_id);

CREATE TABLE IF NOT EXISTS public.ground_truth_timestamps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL,
    timestamp_seconds INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_ground_truth_timestamps_video
        FOREIGN KEY (video_id)
        REFERENCES public.videos (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_ground_truth_timestamps_nonnegative
        CHECK (timestamp_seconds >= 0),
    CONSTRAINT uq_ground_truth_timestamps_video_time
        UNIQUE (video_id, timestamp_seconds)
);